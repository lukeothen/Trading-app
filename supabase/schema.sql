-- Fence Mate activity tracking table.
-- Safe for both a new install and an existing table created with older columns.
create table if not exists public.fence_mate_activity (
 id bigint generated by default as identity primary key
);

alter table public.fence_mate_activity
 add column if not exists event_type text,
 add column if not exists details jsonb not null default '{}'::jsonb,
 add column if not exists created_at timestamptz not null default now();

-- Backfill rows if the table already existed before tracking was installed.
update public.fence_mate_activity
set event_type = 'feature_opened'
where event_type is null;

alter table public.fence_mate_activity
 alter column event_type set default 'feature_opened',
 alter column event_type set not null;

do $$
begin
 if not exists (
  select 1 from pg_constraint
  where conname = 'fence_mate_activity_event_type_check'
    and conrelid = 'public.fence_mate_activity'::regclass
 ) then
  alter table public.fence_mate_activity
   add constraint fence_mate_activity_event_type_check
   check (event_type in (
    'feature_opened','calculation_completed','ai_used',
    'job_saved','estimate_saved','feedback_submitted'
   ));
 end if;
end $$;

alter table public.fence_mate_activity enable row level security;
revoke all on table public.fence_mate_activity from anon, authenticated;
