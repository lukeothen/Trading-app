-- Fence Mate activity tracking schema.
-- Compatible with the earlier table variant that requires tester_id and event_name.
create table if not exists public.fence_mate_activity (
 id bigint generated by default as identity primary key,
 tester_id uuid,
 event_name text,
 event_type text,
 details jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now()
);

alter table public.fence_mate_activity
 add column if not exists tester_id uuid,
 add column if not exists event_name text,
 add column if not exists event_type text,
 add column if not exists details jsonb not null default '{}'::jsonb,
 add column if not exists created_at timestamptz not null default now();

-- Backfill fields on tables created by older versions before applying NOT NULL.
update public.fence_mate_activity
set event_type = coalesce(event_type, event_name, 'feature_opened'),
    event_name = coalesce(event_name, event_type, 'feature_opened')
where event_type is null or event_name is null;

alter table public.fence_mate_activity
 alter column event_type set default 'feature_opened',
 alter column event_type set not null,
 alter column event_name set default 'feature_opened',
 alter column event_name set not null;

-- Keep event values constrained to the labels the app emits.
do $$
begin
 if not exists (
  select 1 from pg_constraint
  where conname = 'fence_mate_activity_event_type_check'
    and conrelid = 'public.fence_mate_activity'::regclass
 ) then
  alter table public.fence_mate_activity
   add constraint fence_mate_activity_event_type_check
   check (event_type in (
    'feature_opened','calculation_completed','ai_used',
    'job_saved','estimate_saved','feedback_submitted'
   ));
 end if;
end $$;

alter table public.fence_mate_activity enable row level security;
revoke all on table public.fence_mate_activity from anon, authenticated;
