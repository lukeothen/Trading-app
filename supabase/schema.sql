-- Fence Mate anonymous product-usage analytics.
-- Run once in Supabase Dashboard -> SQL Editor.
-- The Netlify Function inserts using a server-side Supabase secret key.
-- Do not expose that key in browser code.

create table if not exists public.fence_mate_activity (
  id bigint generated by default as identity primary key,
  event_type text not null check (
    event_type in (
      'feature_opened',
      'calculation_completed',
      'ai_used',
      'job_saved',
      'estimate_saved',
      'feedback_submitted'
    )
  ),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

alter table public.fence_mate_activity enable row level security;

-- No anon/authenticated policies are created. Browser clients cannot read,
-- insert, update, or delete rows directly. The Netlify Function uses the
-- server-side secret key, stored in Netlify environment variables.
revoke all on table public.fence_mate_activity from anon, authenticated;
